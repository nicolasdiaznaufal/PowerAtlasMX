// Derives the service-worker precache list from the real module graph (static + dynamic imports from main.js),
// the stylesheets in index.html, fonts in tokens.css and the fixed assets below.
//   node web/v2/tools/precache-manifest.mjs          -> prints the list
//   node web/v2/tools/precache-manifest.mjs --write  -> writes web/v2/precache.js (classic script for importScripts)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const V2 = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WEB = resolve(V2, '..');
const IMPORT = /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)['"]([^'"]+\.m?js)['"]/g;

export function moduleGraph(entry = join(V2, 'main.js')) {
  const seen = new Set(), queue = [entry];
  while (queue.length) {
    const f = queue.pop();
    if (seen.has(f)) continue;
    seen.add(f);
    for (const m of readFileSync(f, 'utf8').matchAll(IMPORT)) {
      if (!m[1].startsWith('.')) continue;
      const t = resolve(dirname(f), m[1]);
      if (t.startsWith(WEB)) queue.push(t);
    }
  }
  return [...seen];
}

/** URLs relative to /v2/ (v1 files appear as ../assets/...). */
export function precacheList() {
  const rel = (abs) => relative(V2, abs).split('\\').join('/');
  const files = new Set(moduleGraph().map(rel));
  const html = readFileSync(join(V2, 'index.html'), 'utf8');
  for (const m of html.matchAll(/href="(assets\/css\/[^"]+\.css)"/g)) files.add(m[1]);
  files.add('index.html'); files.add('offline.html'); files.add('config.js');
  files.add('assets/fonts/Geist-Variable.woff2'); files.add('assets/fonts/GeistMono-Variable.woff2');
  files.add('assets/img/hero-sun-1000.webp'); files.add('assets/img/hero-sun-2000.webp'); files.add('assets/icons/eclipse.svg');
  files.add('assets/img/clients/manifest.json'); files.add('assets/vendor/deckgl/deck.min.js'); files.add('../assets/geo/mx.json');
  // appendix equations: KaTeX is vendored under web/assets/vendor/katex (v1); js, css and the woff2 fonts the css names
  const kdir = join(WEB, 'assets/vendor/katex'), kcss = join(kdir, 'katex.min.css');
  if (existsSync(kcss)) {
    files.add('../assets/vendor/katex/katex.min.css'); files.add('../assets/vendor/katex/katex.min.js');
    for (const m of readFileSync(kcss, 'utf8').matchAll(/url\(([^)]*?\.woff2)\)/g)) files.add(`../assets/vendor/katex/${m[1].replace(/^["']|["']$/g, '')}`);
  }
  return ['./', ...[...files].sort()];
}

/** sha256 over (path, content) of every precached file (index.html stands for './'); 8 hex chars are put in the cache version. */
export function contentHash(list = precacheList()) {
  const h = createHash('sha256');
  for (const u of list) {
    const f = join(V2, u === './' ? 'index.html' : u);
    h.update(u).update('\0').update(existsSync(f) ? readFileSync(f) : 'MISSING').update('\0');
  }
  return h.digest('hex').slice(0, 8);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const list = precacheList();
  if (process.argv.includes('--write')) {
    writeFileSync(join(V2, 'precache.js'), `// GENERATED by tools/precache-manifest.mjs (a test fails when it is stale). Paths are relative to /v2/.\nself.PRECACHE = ${JSON.stringify(list, null, 1)};\n`);
    const swPath = join(V2, 'sw.js'), hash = contentHash(list);
    const sw = readFileSync(swPath, 'utf8').replace(/const VERSION = '(v2-[a-z0-9]+-\d+)(?:-[0-9a-f]{8})?';/, `const VERSION = '$1-${hash}';`);
    writeFileSync(swPath, sw);
    console.log(`wrote ${list.length} entries, content hash ${hash}`);
  } else console.log(list.join('\n'));
}
